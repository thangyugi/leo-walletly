#!/usr/bin/env node
// Generates types/supabase.ts from a live Postgres (local or Supabase) using psql.
//
//   DATABASE_URL=postgresql://postgres@localhost:54322/postgres node scripts/gen-db-types.mjs
//
// Output follows the shape of `supabase gen types typescript` (Tables / Views /
// Functions with Row / Insert / Update / Relationships) so it can be swapped for
// the official generator once a Supabase project is linked.
import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const url = process.env.DATABASE_URL
if (!url) {
  console.error('Set DATABASE_URL')
  process.exit(1)
}

const sql = (query) =>
  JSON.parse(execFileSync('psql', [url, '-X', '-A', '-t', '-c', `select coalesce(json_agg(x), '[]') from (${query}) x`], { encoding: 'utf8' }))

const columns = sql(`
  select c.relname as rel, c.relkind as kind, a.attname as name, a.attnum as num,
         format_type(a.atttypid, a.atttypmod) as type, t.typcategory as cat,
         et.typname as elem, t.typname as typname,
         not a.attnotnull as nullable,
         (a.atthasdef or a.attidentity <> '') as has_default
  from pg_attribute a
  join pg_class c on c.oid = a.attrelid
  join pg_namespace n on n.oid = c.relnamespace
  join pg_type t on t.oid = a.atttypid
  left join pg_type et on et.oid = t.typelem and t.typcategory = 'A'
  where n.nspname = 'public' and c.relkind in ('r', 'v') and a.attnum > 0 and not a.attisdropped
  order by c.relname, a.attnum`)

const fks = sql(`
  select con.conname as name, c.relname as rel, rc.relname as ref,
         (select json_agg(a.attname order by k.ord) from unnest(con.conkey) with ordinality k(attnum, ord)
            join pg_attribute a on a.attrelid = con.conrelid and a.attnum = k.attnum) as cols,
         (select json_agg(a.attname order by k.ord) from unnest(con.confkey) with ordinality k(attnum, ord)
            join pg_attribute a on a.attrelid = con.confrelid and a.attnum = k.attnum) as ref_cols,
         exists (select 1 from pg_index i where i.indrelid = con.conrelid and i.indisunique
                   and i.indkey::int2[] @> con.conkey and array_length(i.indkey::int2[], 1) = array_length(con.conkey, 1)) as one_to_one
  from pg_constraint con
  join pg_class c on c.oid = con.conrelid
  join pg_class rc on rc.oid = con.confrelid
  join pg_namespace n on n.oid = c.relnamespace
  join pg_namespace rn on rn.oid = rc.relnamespace
  where con.contype = 'f' and n.nspname = 'public' and rn.nspname = 'public'
  order by c.relname, con.conname`)

const functions = sql(`
  select p.proname as name, p.proretset as returns_set, t.typname as ret_type, t.typtype as ret_kind,
         t.typcategory as ret_cat, rel.relname as ret_rel,
         coalesce(p.proargnames, '{}') as arg_names,
         coalesce((select json_agg(format_type(x, null)) from unnest(coalesce(p.proallargtypes, p.proargtypes::oid[])) x), '[]') as arg_types,
         coalesce(p.proargmodes::text[], '{}') as arg_modes,
         p.pronargdefaults as n_defaults, p.pronargs as n_args
  from pg_proc p
  join pg_namespace n on n.oid = p.pronamespace
  join pg_type t on t.oid = p.prorettype
  left join pg_class rel on rel.oid = t.typrelid
  where n.nspname = 'public' and p.prokind = 'f'
    and t.typname <> 'trigger'
    and has_function_privilege('authenticated', p.oid, 'execute')
  order by p.proname`)

function tsType(pgType) {
  const t = pgType.replace(/\(.*\)/, '').replace(/^extensions\./, '').trim()
  if (t.endsWith('[]')) return `${tsType(t.slice(0, -2))}[]`
  if (['smallint', 'integer', 'bigint', 'numeric', 'real', 'double precision'].includes(t)) return 'number'
  if (t === 'boolean') return 'boolean'
  if (t === 'jsonb' || t === 'json') return 'Json'
  return 'string'
}

const byRel = new Map()
for (const c of columns) {
  if (!byRel.has(c.rel)) byRel.set(c.rel, { kind: c.kind, cols: [] })
  byRel.get(c.rel).cols.push(c)
}

const rels = (name) =>
  fks.filter((f) => f.rel === name).map((f) =>
    `          {\n            foreignKeyName: ${JSON.stringify(f.name)}\n            columns: ${JSON.stringify(f.cols)}\n            isOneToOne: ${f.one_to_one}\n            referencedRelation: ${JSON.stringify(f.ref)}\n            referencedColumns: ${JSON.stringify(f.ref_cols)}\n          },`
  ).join('\n')

const out = []
out.push('// GENERATED by scripts/gen-db-types.mjs — do not edit by hand.')
out.push('// Source: supabase/migrations (schema v2.1). Regenerate after every migration change.')
out.push('')
out.push('export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[]')
out.push('')
out.push('export type Database = {')
out.push('  public: {')
out.push('    Tables: {')
for (const [name, rel] of byRel) {
  if (rel.kind !== 'r') continue
  out.push(`      ${name}: {`)
  out.push('        Row: {')
  for (const c of rel.cols) out.push(`          ${c.name}: ${tsType(c.type)}${c.nullable ? ' | null' : ''}`)
  out.push('        }')
  out.push('        Insert: {')
  for (const c of rel.cols) out.push(`          ${c.name}${c.nullable || c.has_default ? '?' : ''}: ${tsType(c.type)}${c.nullable ? ' | null' : ''}`)
  out.push('        }')
  out.push('        Update: {')
  for (const c of rel.cols) out.push(`          ${c.name}?: ${tsType(c.type)}${c.nullable ? ' | null' : ''}`)
  out.push('        }')
  out.push('        Relationships: [')
  const r = rels(name)
  if (r) out.push(r)
  out.push('        ]')
  out.push('      }')
}
out.push('    }')
out.push('    Views: {')
for (const [name, rel] of byRel) {
  if (rel.kind !== 'v') continue
  out.push(`      ${name}: {`)
  out.push('        Row: {')
  for (const c of rel.cols) out.push(`          ${c.name}: ${tsType(c.type)} | null`)
  out.push('        }')
  out.push('        Relationships: []')
  out.push('      }')
}
out.push('    }')
out.push('    Functions: {')
const seen = new Set()
for (const f of functions) {
  if (seen.has(f.name)) continue
  seen.add(f.name)
  const modes = f.arg_modes.length ? f.arg_modes : f.arg_types.map(() => 'i')
  const args = []
  const retCols = []
  f.arg_types.forEach((type, i) => {
    const argName = f.arg_names[i] || `arg${i}`
    if (modes[i] === 'i' || modes[i] === 'b') {
      const inputIndex = args.length
      const optional = inputIndex >= f.n_args - f.n_defaults
      args.push(`          ${argName}${optional ? '?' : ''}: ${tsType(type)}${optional ? ' | null' : ''}`)
    } else if (modes[i] === 't' || modes[i] === 'o') {
      retCols.push(`            ${argName}: ${tsType(type)}`)
    }
  })
  let returns
  if (retCols.length) returns = `{\n${retCols.join('\n')}\n          }[]`
  else if (f.ret_rel) returns = `Database['public']['Tables'][${JSON.stringify(f.ret_rel)}]['Row']${f.returns_set ? '[]' : ''}`
  else if (f.ret_type === 'void') returns = 'undefined'
  else returns = `${tsType(f.ret_type === 'bpchar' || f.ret_type === 'varchar' ? 'text' : f.ret_type === 'int4' || f.ret_type === 'int2' || f.ret_type === 'int8' || f.ret_type === 'numeric' ? 'integer' : f.ret_type === 'bool' ? 'boolean' : f.ret_type)}${f.returns_set ? '[]' : ''}`
  out.push(`      ${f.name}: {`)
  out.push(args.length ? `        Args: {\n${args.join('\n')}\n        }` : '        Args: Record<PropertyKey, never>')
  out.push(`        Returns: ${returns}`)
  out.push('      }')
}
out.push('    }')
out.push('    Enums: {')
out.push('      [_ in never]: never')
out.push('    }')
out.push('    CompositeTypes: {')
out.push('      [_ in never]: never')
out.push('    }')
out.push('  }')
out.push('}')
out.push('')
out.push(`type PublicSchema = Database['public']`)
out.push(`export type Tables<T extends keyof PublicSchema['Tables']> = PublicSchema['Tables'][T]['Row']`)
out.push(`export type TablesInsert<T extends keyof PublicSchema['Tables']> = PublicSchema['Tables'][T]['Insert']`)
out.push(`export type TablesUpdate<T extends keyof PublicSchema['Tables']> = PublicSchema['Tables'][T]['Update']`)
out.push(`export type Views<T extends keyof PublicSchema['Views']> = PublicSchema['Views'][T]['Row']`)
out.push(`export type Functions<T extends keyof PublicSchema['Functions']> = PublicSchema['Functions'][T]`)
out.push('')

writeFileSync(path.join(root, 'types/supabase.ts'), out.join('\n'))
console.log(`types/supabase.ts: ${[...byRel.values()].filter((r) => r.kind === 'r').length} tables, ${[...byRel.values()].filter((r) => r.kind === 'v').length} views, ${seen.size} functions`)
