#!/usr/bin/env node
// Generates supabase/migrations_v2/20260928000016_seed_translations.sql from lib/i18n.ts.
//
//   node scripts/generate-translation-seed.mjs
//
// lib/i18n.ts stays the authoring source for UI strings (typed, reviewed in PRs);
// the database copy is what the app reads at runtime and what users override.
// Arrays (e.g. calendar.days) become one key per item: calendar.days.0 … .6.
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import path from 'node:path'
import ts from 'typescript'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const source = readFileSync(path.join(root, 'lib/i18n.ts'), 'utf8')
const { outputText } = ts.transpileModule(source, {
  compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2020 },
})
const mod = await import('data:text/javascript;base64,' + Buffer.from(outputText).toString('base64'))
const { TRANSLATIONS } = mod

// Namespaces whose strings users may rename on screen (menu items, page titles,
// KPI and column labels). Everything else (errors, validation, legal) is locked.
const USER_EDITABLE = new Set([
  'nav', 'dashboard', 'transactions', 'calendar', 'analytics', 'recurring', 'report',
  'scan', 'import', 'groups', 'categories', 'accounts', 'budget',
])

function flatten(obj, prefix = '', out = {}) {
  for (const [k, v] of Object.entries(obj)) {
    const key = prefix ? `${prefix}.${k}` : k
    if (Array.isArray(v)) v.forEach((item, i) => { out[`${key}.${i}`] = String(item) })
    else if (v && typeof v === 'object') flatten(v, key, out)
    else if (v != null) out[key] = String(v)
  }
  return out
}

const langs = Object.keys(TRANSLATIONS)
const flat = Object.fromEntries(langs.map((l) => [l, flatten(TRANSLATIONS[l])]))
const keys = [...new Set(langs.flatMap((l) => Object.keys(flat[l])))].sort()

const q = (s) => `'${String(s).replace(/'/g, "''")}'`
const placeholders = (key) => {
  const names = new Set()
  for (const l of langs) for (const m of (flat[l][key] ?? '').matchAll(/\{\{\s*(\w+)\s*\}\}/g)) names.add(m[1])
  return names.size ? q([...names].join(',')) : 'null'
}

const lines = []
lines.push('-- GENERATED by scripts/generate-translation-seed.mjs from lib/i18n.ts — do not edit by hand.')
lines.push('-- Languages + UI translation keys/values (ja, vi, en).')
lines.push('')
lines.push(`insert into public.languages (code, locale, name, native_name, short_label, fallback_code, is_active, is_default, sort_order) values
  ('en', 'en-US', 'English', 'English', 'EN', null, true, false, 3),
  ('ja', 'ja-JP', 'Japanese', '日本語', 'JA', 'en', true, true, 1),
  ('vi', 'vi-VN', 'Vietnamese', 'Tiếng Việt', 'VI', 'en', true, false, 2)
on conflict (code) do nothing;`)
lines.push('')

const chunk = 400
for (let i = 0; i < keys.length; i += chunk) {
  const part = keys.slice(i, i + chunk)
  lines.push('insert into public.translation_keys (key, namespace, placeholders, is_user_editable) values')
  lines.push(part.map((k) => {
    const ns = k.split('.')[0]
    return `  (${q(k)}, ${q(ns)}, ${placeholders(k)}, ${USER_EDITABLE.has(ns)})`
  }).join(',\n'))
  lines.push('on conflict (key) do nothing;')
  lines.push('')
}

for (const l of langs) {
  const entries = keys.filter((k) => flat[l][k] != null)
  for (let i = 0; i < entries.length; i += chunk) {
    const part = entries.slice(i, i + chunk)
    lines.push('insert into public.translations (key, language_code, value) values')
    lines.push(part.map((k) => `  (${q(k)}, ${q(l)}, ${q(flat[l][k])})`).join(',\n'))
    lines.push('on conflict (key, language_code) do nothing;')
    lines.push('')
  }
}

const out = path.join(root, 'supabase/migrations_v2/20260928000016_seed_translations.sql')
writeFileSync(out, lines.join('\n'))
console.log(`Wrote ${keys.length} keys × ${langs.length} languages → ${path.relative(root, out)}`)
